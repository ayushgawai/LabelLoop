"""QR readability gate: run inside X2Real, put a parcel (default box_z95112) label-towards-camera at fixed distances in front
of a wrist camera, grab frames, save PNGs and decode them with zxing-cpp.

  python sim/qr_gate.py --env artixon_arm6a_G_labelloop_qr_sort_case18_id_env --out C:\\x2\\logs\\qr_gate \\
      [--cam right_wrist_camera] [--dist-cm 10,15,20,25,30] [--frames 10]

Needs a running policy server (zero-action template) like any x2real_eval run, and a suite yaml generated by
x2real_eval.py (copy a leftover manaenv/defination/_x2real_eval_*.yaml, pass as --config). Hooks AFTER_STEP via
register_global_runner_hook, so it replays main.py in-process. Run from the X2Real checkout.
"""
import argparse
import json
import os
import runpy
import sys
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--config", required=True)
ap.add_argument("--env", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--cam", default="right_wrist_camera")
ap.add_argument("--box", default="box_z95112")
ap.add_argument("--dist-cm", default="10,15,20,25,30")
ap.add_argument("--frames", type=int, default=10)
ap.add_argument("--up", type=float, default=0.0, help="shift label up in the image by this fraction of d (fingers block the lower half)")
ap.add_argument("--warmup", type=int, default=15, help="steps before the first measurement")
A = ap.parse_args()

from manaenv.utils.isaac_runtime_env import reexec_with_isaac_runtime_env  # noqa: E402

reexec_with_isaac_runtime_env()  # re-execs this script when needed, so the hook below survives

from manaenv.pipeline.runtime.env_runner import AFTER_STEP, register_global_runner_hook  # noqa: E402

OUT = Path(A.out)
OUT.mkdir(parents=True, exist_ok=True)
DISTS = [int(x) for x in A.dist_cm.split(",")]
SETTLE = 3  # steps with the box pinned before frames are taken
st = {"step": 0, "results": {}, "frames": []}


def pose_for(cam, d):
    """Box centre d m along the camera axis, top face (+Z, label) towards the camera, label upright in the image.
    Box x = image right, box y = image up, box z = towards camera (ROS convention: x right, y down, z forward)."""
    import torch
    from isaaclab.utils.math import quat_from_matrix

    pos = cam.data.pos_w[0]
    r = cam.data.quat_w_ros[0]  # camera -> world
    from isaaclab.utils.math import matrix_from_quat

    R = matrix_from_quat(r.unsqueeze(0))[0]
    right, down, fwd = R[:, 0], R[:, 1], R[:, 2]
    top = pos + fwd * (d + 0.03) - down * (A.up * d)  # label face (+Z of box, half height 30 mm) sits d from the camera
    Rb = torch.stack([right, -down, -fwd], dim=1)
    return top, quat_from_matrix(Rb.unsqueeze(0))[0], pos, R


def hook(ctx, obs, terminated, truncated, actions):
    import numpy as np
    import torch
    import zxingcpp
    from PIL import Image

    env = ctx.gym_env.unwrapped
    st["step"] += 1
    n = st["step"] - A.warmup
    if n < 0:
        return
    per = SETTLE + A.frames
    i, k = divmod(n, per)
    if i >= len(DISTS):
        (OUT / "results.json").write_text(json.dumps(st["results"], indent=1))
        print("QRGATE", json.dumps(st["results"]), flush=True)
        ctx.stop_requested = True
        return
    d = DISTS[i] / 100.0
    cam, box = env.scene.sensors[A.cam], env.scene[A.box]
    p, q, cpos, R = pose_for(cam, d)
    pose = torch.cat([p, q]).unsqueeze(0).to(env.device)
    box.write_root_pose_to_sim_index(root_pose=pose)
    box.write_root_velocity_to_sim_index(root_velocity=torch.zeros(1, 6, device=env.device))
    if k == 0 and i == 0:
        print("QRGATE cam pos", cpos.tolist(), "fwd", R[:, 2].tolist(), "rgb keys", list(cam.data.output.keys()), flush=True)
    if k < SETTLE:
        return
    img = cam.data.output["rgb"][0].detach().cpu().numpy()[..., :3].astype(np.uint8)
    res = st["results"].setdefault(str(DISTS[i]), {"decoded": 0, "frames": 0, "px": []})
    got = [r for r in zxingcpp.read_barcodes(np.ascontiguousarray(img)) if r.text.startswith("420/")]
    res["frames"] += 1
    res["decoded"] += int(len(got) > 0)
    if got:  # symbol width in image px (top-left to top-right corner)
        pos = got[0].position
        res["px"].append(round(float(np.hypot(pos.top_right.x - pos.top_left.x, pos.top_right.y - pos.top_left.y)), 1))
    if k in (SETTLE, SETTLE + 1):
        Image.fromarray(img).save(OUT / f"{A.cam}_{DISTS[i]}cm_{k - SETTLE}.png")


register_global_runner_hook(AFTER_STEP, hook, priority=200)
main_py = str(Path("manaenv/scripts/main.py").resolve())
sys.argv = [main_py, "--config", A.config, "--env-name", A.env, "--seed", "42", "--policy-config",
            "policy/x2real_ps@v1.0.0.yaml", "--server-address", "127.0.0.1", "--server-port", "8001", "--enable_cameras"]
runpy.run_path(main_py, run_name="__main__")
